/**
 * 格子奥側の画面共有パネルを一面だけ置くための配置定数。
 *
 * 描画と開始・停止の操作は公式の `ScreenShareDisplay` が担い、
 * ワールド側は共有状態を所有しない。開始・停止は部品標準の
 * Interact操作をそのまま使い、独自の実装を足さない。
 * 配置の具体値（`id`・ワールド座標・向き・幅）はここの定数に集め、
 * `World.tsx` は格子奥側の中央に置くだけにする。
 * 更新レート上限（`targetFps`）は部品の既定（制限なし）のまま渡さず、
 * 実機の負荷を見て決める。プレースホルダー画像は採用しない。
 *
 * @packageDocumentation
 */

/**
 * 画面共有パネルの識別子。
 * 格子・方向・次元の `Interactable`（`pitch-grid-*`）と重ならない一意値である。
 */
export const SCREEN_SHARE_ID = 'screen-share-main';

/**
 * 画面共有パネルの配置位置（ワールド座標）。
 * 奥壁の内側面（z≈-19.75）の手前に寄せ、x を中央に置く。
 * 右側の理論説明パネルと投影上も重ならないようにする。
 * 壁の内側・地面より上に収める。スポーン正面では格子越しになるが遮蔽は許容する（人間判断）。
 * 実画面の確認で調整する暫定値である。
 */
export const SCREEN_SHARE_POSITION: readonly [number, number, number] = [0, 2.5, -19.4];

/**
 * 画面共有パネルの向き。面の既定の正面（+z）を訪問者側へ向けるため回転しない。
 * 回転を付けないことを明示し、向きの検査対象にする。
 */
export const SCREEN_SHARE_ROTATION: readonly [number, number, number] = [0, 0, 0];

/**
 * 画面共有パネルの幅。高さは16:9で部品が自動計算する。
 * 奥壁の高さ（5）に収まる最大近傍の暫定値である（幅8.5で高さ約4.78）。
 * 実画面の確認で調整する。
 */
export const SCREEN_SHARE_WIDTH = 8.5;
